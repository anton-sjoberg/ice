        public bool gameActive;
        public bool gameStarted;
        public bool gamePaused;
        public bool gameFinished;

        public void Initialize()
        {
            gameActive = false;
            gameStarted = false;
            gamePaused = false;
            gameFinished = false;

            currentLevel = 0;
            LoadLevel(currentLevel);
        }

        // Laddar en specifik nivå baserat på index
        private void LoadLevel(int levelIndex)
        {
            if (levelIndex >= 0 && levelIndex < levels.Count)
            {
                _tileMap.tileMap = levels[levelIndex];
                _tileMap.mapWidth = _tileMap.tileMap.GetLength(1);
                _tileMap.mapHeight = _tileMap.tileMap.GetLength(0);
                _player.position.X = currentLevel == 0 ? 100 : 0;

                for (int i = _particleManager.snowflakes.Count - 1; i >= 0; i--)
                {
                    _particleManager.snowflakes[i].Position.X = random.Next(0, _graphicsDevice.Viewport.Width - _particleManager.snowflakeSize);
                }

                for (int i = _particleManager.snowflakes.Count - 1; i >= 0; i--)
                {
                    if (_particleManager.snowflakes[i].Position.Y > _graphicsDevice.Viewport.Height || _particleManager.SnowIntersectsObject(_particleManager.snowflakes[i].Position)) _particleManager.snowflakes.RemoveAt(i);
                }
            }

            while (_player.PlayerIntersectsSolid(_player.position)) { _player.averageVelocity.Y = 0;  _player.position.Y -= 0.1f; }
        }

        // Kollar om spelaren har klarat nivån
        private void CheckForLevelComplete(Vector2 pos)
        {
            if (pos.X > _graphicsDevice.Viewport.Width - _player.playerSize * 0.5f || (canSkip && keyboardState.IsKeyDown(Keys.R)))
            {
                canSkip = false;

                currentLevel++;

                if (currentLevel < levels.Count)
                {
                    LoadLevel(currentLevel);
                }
                else
                {
                    currentLevel = 0;
                    LoadLevel(currentLevel);

                    _player.velocity = Vector2.Zero;
                    _player.position.Y = 720;

                    _player.hasMoved = false;
                    gameFinished = true;
                }
            }
            else if (keyboardState.IsKeyUp(Keys.R)) canSkip = true;
        }

        // Återgår till huvudmenyn och återställer tillstånd
        public void ReturnToMainMenu()
        {
            gameActive = false;
            gameStarted = false;
            gamePaused = false;
            gameFinished = false;

            currentLevel = 0;
            LoadLevel(currentLevel);

            _player.velocity = Vector2.Zero;
            _player.position.Y = 720;

            _player.hasMoved = false;
        }

        // Uppdaterar nivålogik varje frame
        public void Update(GameTime gameTime)
        {
            keyboardState = Keyboard.GetState();

            if (!gameStarted || gameFinished) gameActive = false;
            else gameActive = true;

            if (gameActive) CheckForLevelComplete(_player.position);
        }
